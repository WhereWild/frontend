// Regenerates content/guides/variables/index.ts and
// content/guides/variables/types/index.ts from whatever .md files exist in
// those directories, so authoring a new guide (or deleting one) needs no
// manual wiring — just add/remove the file and this picks it up.

import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

function generateBarrel({ dir, exportName, scriptComment }) {
  const indexPath = join(dir, 'index.ts');
  mkdirSync(dir, { recursive: true });

  const slugs = readdirSync(dir)
    .filter((name) => name.endsWith('.md'))
    .map((name) => name.slice(0, -'.md'.length))
    .sort();

  const header = `// SPDX-FileCopyrightText: 2025-2026 The WhereWild Contributors (see CONTRIBUTORS)
//
// SPDX-License-Identifier: AGPL-3.0-or-later

// AUTO-GENERATED by scripts/generate-variable-guides-index.mjs — do not edit
// by hand. Add or remove a .md file in this directory and re-run
// \`npm run sync:variable-guides\` (or \`npm run typecheck\`/\`npm run web\`,
// which already do) to regenerate this file.
`;

  const imports = slugs
    .map((slug) => `import v_${slug} from './${slug}.md';`)
    .join('\n');

  const entries = slugs.map((slug) => `  '${slug}': v_${slug},`).join('\n');

  const body = `
export const ${exportName}: Record<string, string> = {
${entries}
};
`;

  const contents = slugs.length
    ? `${header}\n${imports}\n${body}`
    : `${header}\nexport const ${exportName}: Record<string, string> = {};\n`;

  writeFileSync(indexPath, contents);
  console.log(
    `[generate-variable-guides-index] Wrote ${slugs.length} ${scriptComment} to ${indexPath}`,
  );
}

const VARIABLES_DIR = join(process.cwd(), 'content', 'guides', 'variables');
const TYPES_DIR = join(VARIABLES_DIR, 'types');

generateBarrel({
  dir: VARIABLES_DIR,
  exportName: 'VARIABLE_GUIDES',
  scriptComment: 'variable guide(s)',
});
generateBarrel({
  dir: TYPES_DIR,
  exportName: 'TYPE_GUIDES',
  scriptComment: 'type guide(s)',
});
