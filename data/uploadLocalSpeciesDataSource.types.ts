/** Optional per-bundle description + taxon image, from upload_metadata.json
 * in the processed ZIP -- see wherewild's util.upload.build_description_
 * profile_for_df/_add_metadata_to_archive. Present for a custom upload only
 * when the user opted in via the upload page's "extra options"; always
 * present for a re-imported species-page download, since a real species
 * already has both. imageUrl is either a remote URL (a species' own hosted
 * photo, or a custom upload's own provided path/URL -- needs network to
 * display) or an object URL for an image embedded directly in the ZIP (a
 * custom upload's own uploaded file -- works fully offline); the parser
 * resolves which one this is, callers don't need to know or care.
 */
export type UploadedDescriptionImage = {
  descriptionSections?: SpeciesOverviewSection[] | null;
  imageUrl?: string | null;
  imageLicense?: string | null;
  imageLicenseUrl?: string | null;
  imageCreator?: string | null;
  imageRightsHolder?: string | null;
};

