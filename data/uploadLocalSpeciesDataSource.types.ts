export class UploadedParquetBundleValidationError extends Error {
  issues: string[];

  constructor(issues: string[]) {
    super(`Uploaded parquet bundle is invalid: ${issues.join(' | ')}`);
    this.name = 'UploadedParquetBundleValidationError';
    this.issues = issues;
  }
}
