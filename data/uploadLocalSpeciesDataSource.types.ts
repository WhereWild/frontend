  catalogAutoGenerated?: boolean;
  /** Optional per-occurrence photo URL, from an image-URL column in the
   * uploaded file (see util/upload.py's normalize_image_column on the
   * backend) — passed straight through to the map popup/gallery the same
   * way a real SpeciesOccurrence's mediaUrl is, no extra fetch involved. */
