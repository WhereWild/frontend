const convertSummaryFields = (
  summary: SpeciesEnvironmentStats['summary'],
  conv: LinearConversion,
): SpeciesEnvironmentStats['summary'] => {
  const pos = (v: number | null | undefined) => applyConv(v, conv);
  const scale = (v: number | null | undefined) => applyConv(v, conv, true);
  return {
    ...summary,
    min: pos(summary.min),
    mean: pos(summary.mean),
    max: pos(summary.max),
    median: pos(summary.median),
    std: scale(summary.std),
    stddev: scale(summary.stddev),
    variance: summary.variance != null ? (conv.scale * conv.scale * summary.variance) : summary.variance,
    range: scale(summary.range),
    q01: pos(summary.q01),
    q10: pos(summary.q10),
    q25: pos(summary.q25),
    q75: pos(summary.q75),
    q90: pos(summary.q90),
    q99: pos(summary.q99),
    iqr: scale(summary.iqr),
    q10_90_range: scale(summary.q10_90_range),
    mode: typeof summary.mode === 'number' ? pos(summary.mode) : summary.mode,
    // rbar, circular_mean, circular_std, unique_classes, entropy, count: unitless — no conversion
  };
};

const convertStats = (
  stats: SpeciesEnvironmentStats,
  conv: LinearConversion,
): SpeciesEnvironmentStats => ({
  ...stats,
  units: conv.unit,
  summary: convertSummaryFields(stats.summary, conv),
  baselineSummary: stats.baselineSummary
    ? convertSummaryFields(stats.baselineSummary, conv)
    : stats.baselineSummary,
  histogram: stats.histogram
    ? { bins: stats.histogram.bins.map((b) => applyConv(b, conv) ?? b), counts: stats.histogram.counts }
    : stats.histogram,
  densityCurve: stats.densityCurve
    ? {
        points: stats.densityCurve.points.map((p) => applyConv(p, conv) ?? p),
        density: stats.densityCurve.density, // normalized by chart — no need to scale
      }
    : stats.densityCurve,
});

export const buildUploadLocalSpeciesDataSource = ({
  bundle,
  speciesId = DEFAULT_SPECIES_ID,
}: BuildLocalSpeciesDataSourceOptions): SpeciesDataSource => {
  validateUploadedParquetBundle(bundle);

  const statsByVariable = buildStatsByVariable(bundle, speciesId);
  const supportedVariableIds = new Set(Object.keys(statsByVariable));
  const occurrences = toSpeciesOccurrences(bundle.occurrences);
  const observationsByCatalog = toObservationsByCatalog(bundle.occurrences);
  const indexRowsByVariable = groupIndexRowsByVariable(bundle.occurrenceIndex);
  const locations = bundle.locations ?? [];
  const locationLookup = buildLocationLookupMaps(locations);

  // Derive parent GID from child GID using GADM format ("AA.N.M_V" → "AA.N_V" → "AA").
  // This avoids name-based lookups which fail when a county shares a name with a state
  // (e.g., "Utah County" in Utah state has GADM name "Utah", shadowing the state in byName).
  const deriveParentGid = (gid: string): string | null => {
    const match = gid.match(/^(.+)\.\d+_\d+$/);
    if (!match) return null;
    const parentCore = match[1];
    if (locationLookup.byGid.has(normalizeLocationToken(parentCore + '_1'))) {
      return parentCore + '_1';
    }
    if (locationLookup.byGid.has(normalizeLocationToken(parentCore))) {
      return parentCore;
    }
    return null;
  };

  // Precompute observation count per location GID and aggregate up to ancestors
  // so fetchSpeciesLocations can sort by count.
  const countByGid = new Map<string, number>();
  for (const row of bundle.occurrences) {
    if (!row.locationGid) continue;
    let current: string | null = row.locationGid;
    while (current) {
      const norm = normalizeLocationToken(current);
      countByGid.set(norm, (countByGid.get(norm) ?? 0) + 1);
      current = deriveParentGid(current);
    }
  }

  return createSpeciesDataSource({
    locationParentIdentityMode: 'gid',
    fetchEnvironmentVariables: async (options) => {
      const rawDefs =
        bundle.variableDefinitions && bundle.variableDefinitions.length > 0
          ? bundle.variableDefinitions.filter((definition) =>
              supportedVariableIds.has(definition.id),
            )
          : Array.from(supportedVariableIds).map((variable) => {
              const stats = statsByVariable[variable];
              return {
                id: variable,
                name: stats.variableName,
                units: stats.units ?? null,
                valueType: stats.variableType ?? null,
                category: null,
                renderMin: null,
                renderMax: null,
              };
            });

      if (options?.units !== 'imperial') return rawDefs;

      return rawDefs.map((def) => {
        const conv = getMetricToImperial(def.units);
        if (!conv) return def;
        return {
          ...def,
          units: conv.unit,
          renderMin: applyConv(def.renderMin, conv) ?? def.renderMin,
          renderMax: applyConv(def.renderMax, conv) ?? def.renderMax,
        };
      });
    },

    fetchSpeciesEnvironment: async (_taxonId, variableId, options) => {
      const stats = statsByVariable[variableId];
      if (!stats) {
        throw new Error(
          `Local upload does not include stats for variable: ${variableId}`,
        );
      }

      const scoped = buildScopedStats({
        stats,
        locationGid: options?.location,
        observationsByCatalog,
        locationLookup,
        indexRows: indexRowsByVariable[variableId] ?? [],
      });

      if (options?.units !== 'imperial') return scoped;
      const conv = getMetricToImperial(scoped.units);
      return conv ? convertStats(scoped, conv) : scoped;
    },

    fetchEnvironmentRangeSlice: async (params) => {
      const indexRows = indexRowsByVariable[params.variableId] ?? [];
      // The occurrence index stores metric values; reverse-convert selection bounds
      // when the caller is working in imperial so the overlap check is apples-to-apples.
      let { min, max } = params;
      if (params.units === 'imperial') {
        const rawStats = statsByVariable[params.variableId];
        const conv = getMetricToImperial(rawStats?.units);
        if (conv) {
          min = reverseConv(min, conv) ?? min;
          max = reverseConv(max, conv) ?? max;
        }
      }
      const catalogs = filterCatalogIdsByLocation(
        collectCatalogsForRange(indexRows, min, max),
        observationsByCatalog,
        locationLookup,
        params.location,
      );
      const observations = pickOccurrenceObservations(
        catalogs,
        observationsByCatalog,
      );

      const response: SpeciesEnvironmentSliceResponse = {
        speciesId,
        variable: params.variableId,
        range: {
          min: params.min,
          max: params.max,
        },
        limit: params.limit ?? null,
        count: observations.length,
        observations,
      };

      return response;
    },

    fetchSpeciesEnvironmentCategorySamples: async (
      _taxonId,
      variableId,
      classValue,
      options,
    ) => {
      const indexRows = indexRowsByVariable[variableId] ?? [];
      const catalogs = filterCatalogIdsByLocation(
        collectCatalogsForCategory(indexRows, classValue),
        observationsByCatalog,
        locationLookup,
        options?.location,
      );
      const observations = pickOccurrenceObservations(
        catalogs,
        observationsByCatalog,
      );

      const response: SpeciesEnvironmentCategorySampleResponse = {
        speciesId,
        variable: variableId,
        classValue,
        count: observations.length,
        observations,
      };

      return response;
    },

    fetchObservationEnvironmentValue: async (
      _taxonId,
      catalogNumber,
      variableId,
      options,
    ) => {
      const stats = statsByVariable[variableId];
      const row = observationsByCatalog[String(catalogNumber)];
      if (!row) {
        return {
          variable: variableId,
          value: null,
          valueLabel: null,
          valueDescription: null,
          units: stats?.units ?? null,
        };
      }

      if (
        !matchesObservationLocation(
          row.locationGid,
          locationLookup,
          options?.location,
        )
      ) {
        return {
          variable: variableId,
          value: null,
          valueLabel: null,
          valueDescription: null,
          units: stats?.units ?? null,
        };
      }

      const rawValue = findObservationEnvironmentValue(
        indexRowsByVariable[variableId] ?? [],
        catalogNumber,
      );
      const conv =
        options?.units === 'imperial' ? getMetricToImperial(stats?.units) : null;
      const value =
        conv && typeof rawValue === 'number'
          ? (applyConv(rawValue, conv) ?? rawValue)
          : rawValue;
      const categoryEntry = findCategoricalDistributionEntry(stats, rawValue);

      return {
        variable: variableId,
        value,
        valueLabel: categoryEntry?.className ?? null,
        valueDescription: categoryEntry?.description ?? null,
        units: conv ? conv.unit : (stats?.units ?? null),
      };
    },

    fetchSpeciesOccurrences: async (_taxonId, options) => {
      const selectedLocation = options?.location;
      const filtered = !selectedLocation
        ? occurrences
        : occurrences.filter((occurrence) => {
            const row = observationsByCatalog[String(occurrence.catalogNumber)];
            if (!row?.locationGid) {
              return false;
            }
            const rowLocation = resolveLocationEntry(
              row.locationGid,
              locationLookup,
            );
            if (!rowLocation) {
              return (
                normalizeLocationToken(row.locationGid) ===
                normalizeLocationToken(selectedLocation)
              );
            }
            return matchesParentLocation(
              rowLocation,
              selectedLocation,
              locationLookup,
            );
          });
      return {
        occurrences: filtered,
        minTimestamp: null,
        maxTimestamp: null,
        phenologyCounts: null,
      };
    },

    fetchSpeciesLocations: async (_taxonId, level, parent, limit = 500) => {
      const normalizedLevel = normalizeLocationLevel(level);
      const filtered = locations.filter((location) => {
        if (
          typeof normalizedLevel === 'number' &&
          location.level !== normalizedLevel
        ) {
          return false;
        }

        if (!parent) {
          return true;
        }

        return matchesParentLocation(location, parent, locationLookup);
      });

      filtered.sort((a, b) => {
        const ca = countByGid.get(normalizeLocationToken(a.gid)) ?? 0;
        const cb = countByGid.get(normalizeLocationToken(b.gid)) ?? 0;
        return cb - ca || a.name.localeCompare(b.name);
      });
      return filtered.slice(0, limit);
    },
  });
};
