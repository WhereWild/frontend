const matchesObservationLocation = (
  rowLocationGid: string | null | undefined,
  locationLookup: ReturnType<typeof buildLocationLookupMaps>,
  locationGid?: string | null,
) => {
  if (!locationGid) {
    return true;
  }

  if (!rowLocationGid) {
    return false;
  }

  const rowLocation = resolveLocationEntry(rowLocationGid, locationLookup);
  if (!rowLocation) {
    return (
      normalizeLocationToken(rowLocationGid) ===
      normalizeLocationToken(locationGid)
    );
  }

  return matchesParentLocation(rowLocation, locationGid, locationLookup);
};

const filterCatalogIdsByLocation = (
  catalogIds: (number | string)[],
  observationsByCatalog: Record<string, UploadedOccurrenceRow>,
  locationLookup: ReturnType<typeof buildLocationLookupMaps>,
  locationGid?: string | null,
) => {
  if (!locationGid) {
    return catalogIds;
  }

  return catalogIds.filter((id) => {
    const rowLocationGid = observationsByCatalog[String(id)]?.locationGid;
    return matchesObservationLocation(
      rowLocationGid,
      locationLookup,
      locationGid,
    );
  });
};

const toSortedNumericValues = (values: number[]) =>
  values.slice().sort((left, right) => left - right);

const quantileFromSortedValues = (values: number[], quantile: number) => {
  if (!values.length) {
    return null;
  }

  const clamped = Math.min(1, Math.max(0, quantile));
  const position = (values.length - 1) * clamped;
  const lowerIndex = Math.floor(position);
  const upperIndex = Math.ceil(position);

  if (lowerIndex === upperIndex) {
    return values[lowerIndex];
  }

  const weight = position - lowerIndex;
  return values[lowerIndex] * (1 - weight) + values[upperIndex] * weight;
};

const buildHistogramFromValues = (
  values: number[],
  desiredBucketCount?: number,
) => {
  if (!values.length) {
    return null;
  }

  const sortedValues = toSortedNumericValues(values);
  const min = sortedValues[0];
  const max = sortedValues[sortedValues.length - 1];
  if (min === max) {
    const spread = Math.max(Math.abs(min) * 0.01, 1e-6);
    return {
      bins: [min - spread, min + spread],
      counts: [sortedValues.length],
    };
  }

  const bucketCount = Math.max(
    1,
    desiredBucketCount ??
      Math.min(12, Math.ceil(Math.sqrt(sortedValues.length))),
  );
  const span = max - min;
  const step = span / bucketCount;
  const bins = Array.from(
    { length: bucketCount + 1 },
    (_, index) => min + step * index,
  );
  const counts = Array.from({ length: bucketCount }, () => 0);

  sortedValues.forEach((value) => {
    const rawIndex = Math.floor(((value - min) / span) * bucketCount);
    const index = Math.min(bucketCount - 1, Math.max(0, rawIndex));
    counts[index] += 1;
  });

  return { bins, counts };
};

const KDE_N_POINTS = 128;
const INV_SQRT_2PI = 1 / Math.sqrt(2 * Math.PI);

const buildGaussianKde = (
  sortedValues: number[],
): { points: number[]; density: number[] } | null => {
  const n = sortedValues.length;
  if (n < 2) return null;

  let minVal = sortedValues[0];
  let maxVal = sortedValues[n - 1];
  if (Math.abs(maxVal - minVal) < 1e-10) {
    const span = Math.abs(minVal) * 0.1 || 1.0;
    minVal -= span;
    maxVal += span;
  }

  const mean = sortedValues.reduce((s, v) => s + v, 0) / n;
  const variance = sortedValues.reduce((s, v) => s + (v - mean) ** 2, 0) / (n - 1);
  const std = Math.sqrt(variance);

  const h = std < 1e-10
    ? (Math.abs(sortedValues[0]) * 0.01 || 0.1)
    : 1.06 * std * Math.pow(n, -0.2);

  const step = (maxVal - minVal) / (KDE_N_POINTS - 1);
  const points: number[] = [];
  const density: number[] = [];

  for (let i = 0; i < KDE_N_POINTS; i++) {
    const x = minVal + i * step;
    let sum = 0;
    for (let j = 0; j < n; j++) {
      const u = (x - sortedValues[j]) / h;
      sum += INV_SQRT_2PI * Math.exp(-0.5 * u * u);
    }
    points.push(x);
    density.push(sum / (n * h));
  }

  return { points, density };
};

// Wrapped Gaussian KDE for circular variables (degrees, [0,360)).
// Matches the backend's _von_mises_kde_curve bandwidth and grid.
const buildCircularKde = (
  values: number[],
): { points: number[]; density: number[] } | null => {
  const n = values.length;
  if (n < 2) return null;

  // Circular std via mean resultant length R
  let sinSum = 0;
  let cosSum = 0;
  for (const v of values) {
    const r = (v * Math.PI) / 180;
    sinSum += Math.sin(r);
    cosSum += Math.cos(r);
  }
  const R = Math.sqrt(sinSum * sinSum + cosSum * cosSum) / n;
  const cstdRad = Math.sqrt(-2 * Math.log(Math.max(R, 1e-10)));
  if (!isFinite(cstdRad) || cstdRad < 1e-6) return null;

  const hRad = Math.max(Math.pow(4 / (3 * n), 0.2) * cstdRad, 0.05);

  const points: number[] = [];
  const density: number[] = [];
  const TWO_PI = 2 * Math.PI;

  for (let i = 0; i < KDE_N_POINTS; i++) {
    const xDeg = (i / KDE_N_POINTS) * 360;
    const xRad = (xDeg * Math.PI) / 180;
    let sum = 0;
    for (const vDeg of values) {
      const vRad = (vDeg * Math.PI) / 180;
      // Wrap difference to [-π, π]
      let d = xRad - vRad;
      d -= TWO_PI * Math.round(d / TWO_PI);
      const u = d / hRad;
      sum += INV_SQRT_2PI * Math.exp(-0.5 * u * u);
    }
    points.push(xDeg);
    density.push(sum / (n * hRad));
  }

  // Normalize so integral over [0, 2π) ≈ 1
  const stepRad = TWO_PI / KDE_N_POINTS;
  const area = density.reduce((s, d) => s + d, 0) * stepRad;
  if (area > 0) {
    for (let i = 0; i < density.length; i++) density[i] /= area;
  }

  return { points, density };
};

const buildScopedCategoricalStats = ({
  stats,
  locationGid,
  observationsByCatalog,
  locationLookup,
  indexRows,
}: {
  stats: SpeciesEnvironmentStats;
  locationGid: string;
  observationsByCatalog: Record<string, UploadedOccurrenceRow>;
  locationLookup: ReturnType<typeof buildLocationLookupMaps>;
  indexRows: UploadedOccurrenceIndexRow[];
}): SpeciesEnvironmentStats => {
  const countsByClass = new Map<string, number>();
  let totalCount = 0;

  indexRows
    .filter((row) => row.mode === 'category')
    .forEach((row) => {
      const scopedObservationIds = filterCatalogIdsByLocation(
        row.observationIds,
        observationsByCatalog,
        locationLookup,
        locationGid,
      );
      if (!scopedObservationIds.length) {
        return;
      }

      const classKey = String(row.classValue ?? '');
      countsByClass.set(
        classKey,
        (countsByClass.get(classKey) ?? 0) + scopedObservationIds.length,
      );
      totalCount += scopedObservationIds.length;
    });

  const baselineDistribution = stats.categoricalDistribution ?? [];
  const categoricalDistribution = Array.from(countsByClass.entries())
    .map(([classValue, count]) => {
      const baseline = baselineDistribution.find(
        (entry) => String(entry.value) === classValue,
      );
      return {
        value: baseline?.value ?? classValue,
        className: baseline?.className ?? classValue,
        description: baseline?.description ?? null,
        color: baseline?.color ?? null,
        count,
        fraction: totalCount > 0 ? count / totalCount : 0,
      };
    })
    .sort((left, right) => right.count - left.count);

  // Compute entropy and mode from filtered distribution
  let entropy: number | null = null;
  let mode: string | null = null;
  if (totalCount > 0) {
    let entropySum = 0;
    let maxCount = -1;
    for (const [classKey, cnt] of countsByClass.entries()) {
      const p = cnt / totalCount;
      if (p > 0) entropySum -= p * Math.log(p);
      if (cnt > maxCount) {
        maxCount = cnt;
        mode = classKey;
      }
    }
    entropy = entropySum;
  }

  return {
    ...stats,
    summary: {
      count: totalCount,
      min: null,
      mean: null,
      max: null,
      stddev: null,
      q01: null,
      q10: null,
      q90: null,
      q99: null,
      entropy,
      unique_classes: countsByClass.size || null,
      mode,
    },
    categoricalDistribution,
    baselineSummary: stats.summary,
    baselineCategoricalDistribution: baselineDistribution,
  };
};

const buildScopedNumericStats = ({
  stats,
  locationGid,
  observationsByCatalog,
  locationLookup,
  indexRows,
}: {
  stats: SpeciesEnvironmentStats;
  locationGid: string;
  observationsByCatalog: Record<string, UploadedOccurrenceRow>;
  locationLookup: ReturnType<typeof buildLocationLookupMaps>;
  indexRows: UploadedOccurrenceIndexRow[];
}): SpeciesEnvironmentStats => {
  const scopedValues = indexRows
    .filter((row) => row.mode === 'range')
    .flatMap((row) => {
      if (typeof row.min !== 'number' || typeof row.max !== 'number') {
        return [];
      }

      const scopedObservationIds = filterCatalogIdsByLocation(
        row.observationIds,
        observationsByCatalog,
        locationLookup,
        locationGid,
      );
      if (!scopedObservationIds.length) {
        return [];
      }

      const value = row.min === row.max ? row.min : (row.min + row.max) / 2;
      return scopedObservationIds.map(() => value);
    });

  const sortedValues = toSortedNumericValues(scopedValues);
  const count = sortedValues.length;
  const min = count ? sortedValues[0] : null;
  const max = count ? sortedValues[count - 1] : null;
  const mean = count
    ? sortedValues.reduce((sum, value) => sum + value, 0) / count
    : null;
  const variance =
    count > 0 && mean !== null
      ? sortedValues.reduce((sum, value) => sum + (value - mean) ** 2, 0) /
        count
      : null;
  const histogram = buildHistogramFromValues(
    sortedValues,
    stats.histogram?.counts.length,
  );

  let circular_mean: number | null = null;
  let rbar: number | null = null;
  let circular_std: number | null = null;
  if (stats.variableType?.toLowerCase() === 'circular' && count > 0) {
    let sinSum = 0;
    let cosSum = 0;
    for (const v of sortedValues) {
      const r = (v * Math.PI) / 180;
      sinSum += Math.sin(r);
      cosSum += Math.cos(r);
    }
    const R = Math.sqrt(sinSum * sinSum + cosSum * cosSum) / count;
    rbar = R;
    circular_mean = ((Math.atan2(sinSum, cosSum) * 180) / Math.PI + 360) % 360;
    const cstdRad = Math.sqrt(-2 * Math.log(Math.max(R, 1e-10)));
    circular_std = isFinite(cstdRad) ? (cstdRad * 180) / Math.PI : null;
  }

  const stddev = variance !== null ? Math.sqrt(variance) : null;
  const q01 = quantileFromSortedValues(sortedValues, 0.01);
  const q10 = quantileFromSortedValues(sortedValues, 0.1);
  const q25 = quantileFromSortedValues(sortedValues, 0.25);
  const median = quantileFromSortedValues(sortedValues, 0.5);
  const q75 = quantileFromSortedValues(sortedValues, 0.75);
  const q90 = quantileFromSortedValues(sortedValues, 0.9);
  const q99 = quantileFromSortedValues(sortedValues, 0.99);
  const iqr = q25 !== null && q75 !== null ? q75 - q25 : null;
  const range = min !== null && max !== null ? max - min : null;
  const q10_90_range = q10 !== null && q90 !== null ? q90 - q10 : null;

  return {
    ...stats,
    summary: {
      count,
      min,
      mean,
      max,
      median,
      stddev,
      std: stddev,
      variance,
      range,
      q01,
      q10,
      q25,
      q75,
      q90,
      q99,
      iqr,
      q10_90_range,
      circular_mean,
      rbar,
      circular_std,
    },
    histogram,
    densityCurve:
      stats.variableType?.toLowerCase() === 'circular'
        ? buildCircularKde(sortedValues)
        : buildGaussianKde(sortedValues),
    baselineSummary: stats.summary,
  };
};

const buildScopedStats = ({
  stats,
  locationGid,
  observationsByCatalog,
  locationLookup,
  indexRows,
}: {
  stats: SpeciesEnvironmentStats;
  locationGid?: string | null;
  observationsByCatalog: Record<string, UploadedOccurrenceRow>;
  locationLookup: ReturnType<typeof buildLocationLookupMaps>;
  indexRows: UploadedOccurrenceIndexRow[];
}): SpeciesEnvironmentStats => {
  if (!locationGid) {
    return stats;
  }

  const isCategorical =
    stats.variableType?.toLowerCase() === 'categorical' ||
    stats.variableType?.toLowerCase() === 'nominal' ||
    stats.variableType?.toLowerCase() === 'ordinal' ||
    (stats.categoricalDistribution?.length ?? 0) > 0;

  if (isCategorical) {
    return buildScopedCategoricalStats({
      stats,
      locationGid,
      observationsByCatalog,
      locationLookup,
      indexRows,
    });
  }

  return buildScopedNumericStats({
    stats,
    locationGid,
    observationsByCatalog,
    locationLookup,
    indexRows,
  });
};

const pickOccurrenceObservations = (
  catalogIds: (number | string)[],
  observationsByCatalog: Record<string, UploadedOccurrenceRow>,
): SpeciesEnvironmentObservation[] => {
  return catalogIds
    .map((id) => observationsByCatalog[String(id)])
    .filter(Boolean)
    .map((row) => ({
      catalogNumber: row.catalogNumber,
      value: null,
      latitude: row.latitude,
      longitude: row.longitude,
    }));
};

