const buildStatsByVariable = (
  bundle: UploadedParquetBundle,
  speciesId: number,
): Record<string, SpeciesEnvironmentStats> => {
  const summaryByVariable = bundle.summaryStats.reduce<
    Record<string, UploadedSummaryStatsRow>
  >((acc, row) => {
    acc[row.variable] = row;
    return acc;
  }, {});

  const densityByVariable = bundle.densityGraph.reduce<
    Record<string, UploadedDensityGraphPoint[]>
  >((acc, row) => {
    if (!acc[row.variable]) {
      acc[row.variable] = [];
    }
    acc[row.variable].push(row);
    return acc;
  }, {});

  const categoricalByVariable = bundle.categoricalStats.reduce<
    Record<string, UploadedCategoricalStatsRow[]>
  >((acc, row) => {
    if (!acc[row.variable]) {
      acc[row.variable] = [];
    }
    acc[row.variable].push(row);
    return acc;
  }, {});

  const ordinalByVariable = bundle.ordinalStats.reduce<
    Record<string, UploadedCategoricalStatsRow[]>
  >((acc, row) => {
    if (!acc[row.variable]) {
      acc[row.variable] = [];
    }
    acc[row.variable].push(row);
    return acc;
  }, {});

  const categoricalLookupByVariableAndMetric = (
    bundle.categoricalValueLookup ?? []
  ).reduce<
    Record<
      string,
      Record<string, { label?: string | null; description?: string | null }>
    >
  >((acc, row) => {
    if (!acc[row.variable]) {
      acc[row.variable] = {};
    }
    acc[row.variable][row.metric] = {
      label: row.label,
      description: row.description,
    };
    return acc;
  }, {});

  const variableDefinitionsById = new Map(
    (bundle.variableDefinitions ?? []).map((definition) => [
      definition.id,
      definition,
    ]),
  );

  const variableIds = new Set<string>([
    ...Object.keys(summaryByVariable),
    ...Object.keys(densityByVariable),
    ...Object.keys(categoricalByVariable),
    ...Object.keys(ordinalByVariable),
  ]);

  return Array.from(variableIds).reduce<
    Record<string, SpeciesEnvironmentStats>
  >((acc, variable) => {
    const summaryRow = summaryByVariable[variable];
    const variableDefinition = variableDefinitionsById.get(variable);
    const densityRows = densityByVariable[variable] ?? [];

    // Ordinal path: class_id-sorted distribution + quantile stats from tall rows.
    const ordinalRows = ordinalByVariable[variable];
    if (ordinalRows) {
      const ordinalLookupByMetric = categoricalLookupByVariableAndMetric[variable] ?? {};
      const metricVal = (m: string) => ordinalRows.find((r) => r.metric === m)?.value ?? null;
      const totalSamples = metricVal('total_samples');
      const classRows = ordinalRows
        .filter((r) => r.metric.startsWith('class_'))
        .map((r) => {
          const classId = parseInt(r.metric.slice(6), 10);
          const fraction = r.value;
          const count = typeof totalSamples === 'number' ? Math.round(totalSamples * fraction) : 0;
          const lookupEntry = ordinalLookupByMetric[r.metric];
          const legendClass = variableDefinition?.legendClasses?.find(
            (cls) => String(cls.id) === String(classId),
          );
          return {
            value: r.metric,
            className: r.metricLabel ?? lookupEntry?.label ?? r.metric,
            description: lookupEntry?.description ?? null,
            color: legendClass?.color ?? null,
            count,
            fraction,
            classId,
          };
        })
        .sort((a, b) => a.classId - b.classId)
        .map(({ classId: _cid, ...rest }) => rest);

      acc[variable] = {
        speciesId,
        variable,
        variableName: summaryRow?.variableName ?? variableDefinition?.name ?? variable,
        units: summaryRow?.units ?? variableDefinition?.units ?? null,
        variableType: 'ordinal',
        summary: {
          count: typeof totalSamples === 'number' ? Math.round(totalSamples) : (summaryRow?.count ?? 0),
          min: null,
          mean: null,
          max: null,
          median: metricVal('median'),
          std: null,
          stddev: null,
          variance: null,
          range: null,
          q01: null,
          q10: metricVal('10th_percentile'),
          q25: metricVal('25th_percentile'),
          q75: metricVal('75th_percentile'),
          q90: metricVal('90th_percentile'),
          q99: null,
          iqr: null,
          q10_90_range: null,
          circular_mean: null,
          rbar: null,
          circular_std: null,
          circular_var: null,
          unique_classes: metricVal('unique_classes'),
          entropy: metricVal('entropy'),
          mode: metricVal('mode'),
        },
        histogram: null,
        densityCurve: null,
        categoricalDistribution: classRows,
      };
      return acc;
    }

    const categoryRows = categoricalByVariable[variable] ?? [];
    const categoryLookupByMetric =
      categoricalLookupByVariableAndMetric[variable] ?? {};
    const totalSamplesRow = categoryRows.find(
      (entry) => entry.metric === 'total_samples',
    );
    const totalSamples =
      totalSamplesRow && Number.isFinite(totalSamplesRow.value)
        ? totalSamplesRow.value
        : null;
    const uniqueClassesRow = categoryRows.find(
      (entry) => entry.metric === 'unique_classes',
    );
    const entropyRow = categoryRows.find((entry) => entry.metric === 'entropy');
    const modeRow = categoryRows.find((entry) => entry.metric === 'mode');
    const classRows = categoryRows.filter(
      (entry) => !isCategoricalAggregateMetric(entry.metric),
    );
    const isCategoricalVariable = classRows.length > 0;

    // Build metric→code map so we can look up legend class colors by numeric id.
    const metricToCode = Object.fromEntries(
      (bundle.categoricalValueLookup ?? [])
        .filter((row) => row.variable === variable)
        .map((row) => [row.metric, row.code]),
    );
    // Reverse map: code → metric name, for resolving aggregate values like mode.
    const codeToMetric = new Map<string, string>();
    for (const [metric, code] of Object.entries(metricToCode)) {
      codeToMetric.set(String(code).trim(), metric);
      const num = Number(code);
      if (Number.isFinite(num)) {
        codeToMetric.set(String(Math.trunc(num)), metric);
      }
    }

    const categoricalDistribution = classRows
      .filter((entry) => Number.isFinite(entry.value))
      .map((entry) => {
        const fraction = entry.value;
        const count =
          typeof totalSamples === 'number' && Number.isFinite(totalSamples)
            ? Math.round(totalSamples * fraction)
            : 0;

        const code = metricToCode[entry.metric];
        const legendClass = code
          ? variableDefinition?.legendClasses?.find(
              (cls) => String(cls.id) === code,
            )
          : null;

        return {
          value: entry.metric,
          className:
            entry.metricLabel ??
            categoryLookupByMetric[entry.metric]?.label ??
            entry.metric,
          description:
            categoryLookupByMetric[entry.metric]?.description ?? null,
          color: legendClass?.color ?? null,
          count,
          fraction,
        };
      });

    const inferredCount =
      typeof totalSamples === 'number' && Number.isFinite(totalSamples)
        ? Math.max(0, Math.round(totalSamples))
        : categoricalDistribution.reduce(
            (sum, entry) =>
              sum + (Number.isFinite(entry.count) ? entry.count : 0),
            0,
          );

    acc[variable] = {
      speciesId,
      variable,
      variableName:
        summaryRow?.variableName ?? variableDefinition?.name ?? variable,
      units: summaryRow?.units ?? variableDefinition?.units ?? null,
      variableType:
        summaryRow?.variableType ??
        variableDefinition?.valueType ??
        (isCategoricalVariable ? 'categorical' : null),
      summary: {
        count: summaryRow?.count ?? inferredCount,
        min: summaryRow?.min ?? null,
        mean: summaryRow?.mean ?? null,
        max: summaryRow?.max ?? null,
        median: summaryRow?.median ?? null,
        std: summaryRow?.std ?? null,
        stddev: summaryRow?.stddev ?? null,
        variance: summaryRow?.variance ?? null,
        range: summaryRow?.range ?? null,
        q01: summaryRow?.q01 ?? null,
        q10: summaryRow?.q10 ?? null,
        q25: summaryRow?.q25 ?? null,
        q75: summaryRow?.q75 ?? null,
        q90: summaryRow?.q90 ?? null,
        q99: summaryRow?.q99 ?? null,
        iqr: summaryRow?.iqr ?? null,
        q10_90_range: summaryRow?.q10_90_range ?? null,
        circular_mean: summaryRow?.circular_mean ?? null,
        rbar: summaryRow?.rbar ?? null,
        circular_std: summaryRow?.circular_std ?? null,
        circular_var: summaryRow?.circular_var ?? null,
        unique_classes:
          summaryRow?.unique_classes ??
          (uniqueClassesRow && Number.isFinite(uniqueClassesRow.value)
            ? uniqueClassesRow.value
            : null),
        entropy:
          summaryRow?.entropy ??
          (entropyRow && Number.isFinite(entropyRow.value)
            ? entropyRow.value
            : null),
        mode: (() => {
          if (summaryRow?.mode != null) return summaryRow.mode;
          if (modeRow == null) return null;
          const raw = String(modeRow.value).trim();
          const trunc = String(Math.trunc(modeRow.value));
          return codeToMetric.get(raw) ?? codeToMetric.get(trunc) ?? raw;
        })(),
      },
      histogram:
        Array.isArray(summaryRow?.bins) && Array.isArray(summaryRow?.counts)
          ? {
              bins: summaryRow.bins,
              counts: summaryRow.counts,
            }
          : null,
      densityCurve:
        densityRows.length > 0
          ? {
              points: densityRows.map((point) => point.value),
              density: densityRows.map((point) => point.density),
            }
          : null,
      categoricalDistribution,
    };
    return acc;
  }, {});
};

const collectCatalogsForRange = (
  indexRows: UploadedOccurrenceIndexRow[],
  min: number,
  max: number,
) => {
  const catalogs = indexRows
    .filter((row) => row.mode === 'range')
    .filter((row) => typeof row.min === 'number' && typeof row.max === 'number')
    .filter((row) => (row.max as number) >= min && (row.min as number) <= max)
    .flatMap((row) => row.observationIds);

  return Array.from(new Set(catalogs.map((id) => String(id))));
};

