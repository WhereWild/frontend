/** Cumulative area share (0..1) at `celsius`, linearly interpolated;
 * clamped to 0 below / 1 above the sampled range. */
export const cdfAt = (cdf: VariableCdf, celsius: number): number => {
  const pos = (celsius - cdf.startC) / cdf.stepC;
  if (pos <= 0) return 0;
  const last = cdf.cdf.length - 1;
  if (pos >= last) return 1;
  const lo = Math.floor(pos);
  const f = pos - lo;
  return cdf.cdf[lo] + f * (cdf.cdf[lo + 1] - cdf.cdf[lo]);
};
